"use client";

import { FormEvent, useState } from "react";
import { useRouter } from "next/navigation";
import Link from "next/link";
import { createClient } from "@/lib/supabase/client";

export default function NewStudentPage() {
  const router = useRouter();

  const [name, setName] = useState("");
  const [email, setEmail] = useState("");
  const [phone, setPhone] = useState("");

  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);

  async function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();

    // Prevent duplicate submissions.
    if (loading) return;

    setError("");
    setLoading(true);

    try {
      const supabase = createClient();

      // Verify the current user's session.
      const {
        data: { user },
        error: authError,
      } = await supabase.auth.getUser();

      if (authError) {
        console.error("Student creation authentication error:", authError);
        setError(
          "We couldn't verify your login. Please try again.",
        );
        return;
      }

      if (!user) {
        router.push("/login");
        return;
      }

      // The database RLS policy verifies tutor_id = auth.uid().
      // Token fields are generated by the database defaults.
      const { error: insertError } = await supabase
        .from("students")
        .insert({
          tutor_id: user.id,
          name: name.trim(),
          email: email.trim() || null,
          phone: phone.trim() || null,
        });

      if (insertError) {
        // Keep database details in server/browser logs, not the UI.
        console.error("Student creation database error:", insertError);

        setError(
          "Unable to add student. Please check your details and try again.",
        );
        return;
      }

      // Navigate only after the database confirms success.
      router.push("/dashboard/students");
      router.refresh();
    } catch (err) {
      // Handles unexpected exceptions, such as network failures.
      console.error("Unexpected student creation error:", err);

      setError(
        "Something went wrong. Please check your connection and try again.",
      );
    } finally {
      // Always reset loading, including early returns and errors.
      setLoading(false);
    }
  }

  return (
    <main className="min-h-screen bg-[#FAFAFA]">
      {/* Top navigation */}
      <header className="border-b border-gray-200 bg-white">
        <div className="mx-auto flex max-w-6xl items-center justify-between px-6 py-4">
          <Link href="/dashboard" className="flex items-center gap-3">
            <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-[#7C3AED] text-lg font-bold text-white">
              S
            </div>

            <div>
              <p className="font-bold text-[#18181B]">
                StudentTracker
              </p>
              <p className="text-xs text-[#71717A]">
                Tutor Dashboard
              </p>
            </div>
          </Link>

          <Link
            href="/dashboard/students"
            className="text-sm font-medium text-[#71717A] transition hover:text-[#7C3AED]"
          >
            ← Students
          </Link>
        </div>
      </header>

      <div className="mx-auto max-w-2xl px-6 py-10">
        {/* Page heading */}
        <div>
          <p className="text-sm font-semibold text-[#7C3AED]">
            STUDENT MANAGEMENT
          </p>

          <h1 className="mt-1 text-3xl font-bold tracking-tight text-[#18181B]">
            Add Student
          </h1>

          <p className="mt-2 text-[#71717A]">
            Add a new student to your tutoring tracker.
          </p>
        </div>

        {/* Form */}
        <form
          onSubmit={handleSubmit}
          className="mt-8 rounded-2xl border border-gray-200 bg-white p-6 shadow-sm sm:p-8"
        >
          {/* Student name */}
          <div>
            <label
              htmlFor="name"
              className="mb-2 block text-sm font-semibold text-[#18181B]"
            >
              Student name
            </label>

            <input
              id="name"
              type="text"
              value={name}
              onChange={(event) => setName(event.target.value)}
              required
              autoFocus
              className="w-full rounded-xl border border-gray-300 px-4 py-3 text-[#18181B] outline-none transition placeholder:text-gray-400 focus:border-[#7C3AED] focus:ring-4 focus:ring-[#F5F3FF]"
              placeholder="e.g. David"
            />
          </div>

          {/* Email */}
          <div className="mt-6">
            <label
              htmlFor="email"
              className="mb-2 block text-sm font-semibold text-[#18181B]"
            >
              Email
              <span className="ml-2 font-normal text-[#71717A]">
                Optional
              </span>
            </label>

            <input
              id="email"
              type="email"
              value={email}
              onChange={(event) => setEmail(event.target.value)}
              className="w-full rounded-xl border border-gray-300 px-4 py-3 text-[#18181B] outline-none transition placeholder:text-gray-400 focus:border-[#7C3AED] focus:ring-4 focus:ring-[#F5F3FF]"
              placeholder="student@example.com"
            />
          </div>

          {/* Phone */}
          <div className="mt-6">
            <label
              htmlFor="phone"
              className="mb-2 block text-sm font-semibold text-[#18181B]"
            >
              Phone number
              <span className="ml-2 font-normal text-[#71717A]">
                Optional
              </span>
            </label>

            <input
              id="phone"
              type="tel"
              value={phone}
              onChange={(event) => setPhone(event.target.value)}
              className="w-full rounded-xl border border-gray-300 px-4 py-3 text-[#18181B] outline-none transition placeholder:text-gray-400 focus:border-[#7C3AED] focus:ring-4 focus:ring-[#F5F3FF]"
              placeholder="e.g. 08012345678"
            />
          </div>

          {/* Safe, user-friendly error message */}
          {error && (
            <div
              role="alert"
              className="mt-6 rounded-xl border border-red-200 bg-red-50 p-4"
            >
              <p className="text-sm font-medium text-red-700">
                Unable to add student
              </p>

              <p className="mt-1 text-sm text-red-600">
                {error}
              </p>
            </div>
          )}

          {/* Actions */}
          <div className="mt-8 flex flex-col-reverse gap-3 sm:flex-row sm:justify-end">
            <button
              type="button"
              onClick={() => router.back()}
              disabled={loading}
              className="rounded-xl border border-gray-300 px-5 py-3 text-sm font-semibold text-[#18181B] transition hover:bg-gray-50 disabled:cursor-not-allowed disabled:opacity-50"
            >
              Cancel
            </button>

            <button
              type="submit"
              disabled={loading}
              className="rounded-xl bg-[#7C3AED] px-5 py-3 text-sm font-semibold text-white shadow-sm transition hover:bg-[#5B21B6] disabled:cursor-not-allowed disabled:opacity-50"
            >
              {loading ? "Adding student..." : "Add Student"}
            </button>
          </div>
        </form>

        {/* Helpful note */}
        <div className="mt-6 rounded-2xl border border-[#E9D5FF] bg-[#F5F3FF] p-5">
          <div className="flex gap-3">
            <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-white text-[#7C3AED] shadow-sm">
              ✓
            </div>

            <div>
              <h2 className="text-sm font-semibold text-[#18181B]">
                What happens next?
              </h2>

              <p className="mt-1 text-sm leading-6 text-[#71717A]">
                After adding the student, you can create a tutoring package
                and start tracking their sessions.
              </p>
            </div>
          </div>
        </div>
      </div>
    </main>
  );
}